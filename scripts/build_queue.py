"""Build launch/queue.md: the single ordered posting queue (3 JAB : 1 HOOK)."""
import re,os
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)));L=f"{R}/launch"
def blocks(text,pat):
  parts=re.split(pat,text,flags=re.M);return parts
# value posts
V=[];t=open(f"{L}/value-posts.md").read()
for m in re.finditer(r"^## (V\d+) \[(JAB|HOOK)\]\n(.*?)(?=^## |\Z)",t,re.M|re.S):
  V.append(dict(id=m[1],kind=m[2],src="value-posts.md",body=m[3].strip()))
# tag posts (skip already-posted n=1)
T=[];t=open(f"{L}/tag-posts.md").read()
for m in re.finditer(r"^## (\d+)\. (@\S+)\n(.*?)(?=^## |\Z)",t,re.M|re.S):
  n=int(m[1]);b=m[3]
  if n==1: continue
  img=re.search(r"Image: (\S+)",b);body="\n".join(l for l in b.strip().splitlines() if not l.startswith("- ")).strip()
  T.append(dict(id=f"T{n}",kind="JAB",src="tag-posts.md",body=body+(f"\n\n_Image: {img[1]}_" if img else "")))
# kit
CUT={"5-2","10-2","12-1","14-2","7-2"}  # pure promo / template / duplicates value posts
HOOK={"1-2","3-2","5-1","11-3"}
K=[];t=open(f"{L}/x-kit.md").read().split("## 3.")[0].split("## 2.")[1];day=None
for m in re.finditer(r"^### Day (\d+)[^\n]*|^\*\*(\d+)\.\*\* (.*?)(?=^\*\*\d+\.\*\*|^### |^---|\Z)",t,re.M|re.S):
  if m[1]: day=m[1];continue
  k=f"{day}-{m[2]}"
  if k in CUT: continue
  K.append(dict(id=f"K{k}",kind="HOOK" if k in HOOK else "JAB",src="x-kit.md",body=m[3].strip()))
jabs_v=[p for p in V if p["kind"]=="JAB"];hooks=[p for p in V if p["kind"]=="HOOK"]
jabs_k=[p for p in K if p["kind"]=="JAB"];hooks_k=[p for p in K if p["kind"]=="HOOK"]
# merge hooks alternating value/kit
H=[];
while hooks or hooks_k:
  if hooks: H.append(hooks.pop(0))
  if hooks_k: H.append(hooks_k.pop(0))
# jab stream: value, tag, kit round robin
J=[];src=[jabs_v,T,jabs_k]
while any(src):
  for s in src:
    if s: J.append(s.pop(0))
Q=[];step=len(J)/(len(H)) if H else 0;nj=0
for h in H:
  while J and nj<round(step*(len(Q)-nj+1)) and (len(Q)-nj)>=0:
    Q.append(J.pop(0));nj+=1
    if nj>=round(step*(len([q for q in Q if q['kind']=='HOOK'])+1)): break
  Q.append(h)
Q+=J
out=["# @PickAPlugin posting queue — THE file the routine reads","",
"Post top to bottom, one per run. Each item id (Q1, Q2, …) is tracked in launch/x-posted.json under \"queue_posts\" as {\"q\": n, \"id\": \"…\", \"posted\": …, \"url\": …}. Next post = lowest Q number not in queue_posts.",
"Post the text exactly (drop the _Image:_ line, attach that image). Threads: post part 1/n, then each next part as a reply to the previous.",
"Generated by scripts/build_queue.py from value-posts.md, tag-posts.md (spotlights 2–13; #1 already posted) and x-kit.md (pure-promo posts cut). Do not regenerate after posting starts without keeping already-posted items at the top.",
f"Counts: {len(Q)} posts, {sum(p['kind']=='JAB' for p in Q)} JAB / {sum(p['kind']=='HOOK' for p in Q)} HOOK.",""]
for i,p in enumerate(Q,1):
  out+=[f"## Q{i} [{p['kind']}] {p['id']} ({p['src']})","",p["body"],""]
open(f"{L}/queue.md","w").write("\n".join(out))
print(len(Q),[p['kind'][0] for p in Q])
